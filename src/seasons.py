def with_year(when, head):
    """Add the year to a month-only date, e.g. 'April' in 2017–18 -> 'April 2018'."""
    if not when or _re.search(r'\b(19|20)\d\d\b', when):
        return when
    m = _re.match(r'\s*([A-Za-z]+)', when)
    if not m:
        return when
    word = m.group(1).lower()
    hm = _re.match(r'(\d{4})(?:–(\d{2}))?$', head)
    if not hm:
        return when
    y1 = int(hm.group(1)); y2 = y1 + 1 if hm.group(2) else y1
    if word in _MONTHS:
        y = y1 if _MONTHS.index(word) >= 8 else y2   # seasons run September to August
    elif word == 'summer':
        y = y2
    else:
        return when
    sep = ', ' if _re.search(r'\d$', when) else ' '
    return f'{when}{sep}{y}'

def _season_pos(when, head):
    """Position of an entry within its season, by its first month (September first for split seasons)."""
    m=_re.search(r'(January|February|March|April|May|June|July|August|September|October|November|December|Summer)', when or '', _re.I)
    if not m: return None
    word=m.group(1).lower(); mo=7 if word=='summer' else _MONTHS.index(word)+1
    split='–' in head
    return (mo-9)%12 if split else mo   # split seasons: Sep=0 ... Aug=11

def render():
    blocks=[]
    for head, note, entries in SEASONS:
        hl=''
        if head in HOSTED:
            logo='<img class="ps-tbc" src="img/theatre-bc.png" alt="Theatre BC" width="34" height="34">' if head==MAINSTAGE else ''
            hl=f'<li class="ps-host-li"><p class="ps-host{" ps-mainstage" if head==MAINSTAGE else ""}">{logo}<span>{HOSTED[head]}</span></p></li>'
            # Zone festivals are held in May; Mainstage 2019 was in July. Place the note where it falls in the season.
            host_pos=_season_pos('July' if head==MAINSTAGE else 'May', head)
        lis=''; placed=not hl
        for when, title, detail in entries:
            pos=_season_pos(when, head)
            if not placed and (HOST_BEFORE[head] in title if head in HOST_BEFORE else (pos is not None and pos>host_pos)):
                lis+=hl; placed=True
            when=with_year(when, head)
            w=f'<span class="ps-when">{when}</span>' if when else ''
            d=f'<span class="ps-detail">{detail}</span>' if detail else ''
            t2=title if '<em>' in title else f'<b>{title}</b>'
            lis+=f'<li>{w}<span class="ps-title">{t2}</span>{d}</li>'
        if not placed: lis+=hl
        n=f'<p class="ps-note">{note}</p>' if note else ''
        after=''
        ps=''.join(f'<a href="img/posters/{f}.jpg" target="_blank" title="{t} poster (opens full size)"><img src="img/posters/{f}-thumb.jpg" alt="{t} poster" height="130" loading="lazy"></a>' for f,t in POSTERS.get(head,[]))
        ps=f'<div class="ps-posters">{ps}</div>' if ps else ''
        blocks.append(f'<div class="ps-season">{ps}<h3>{head}</h3>{n}<ul>{lis}</ul>{after}</div>')
    mus=''.join(f'<li><span class="ps-when">{y} · {m}</span><span class="ps-title"><em>{t.replace(" (panto)","")}</em>{" (panto)" if "(panto)" in t else ""}</span></li>' for y,m,t in MUSICALS)
    mps=''.join(f'<div class="ps-pfig"><span class="ps-when ps-pyear">{f[:4]}</span><a href="img/posters/{f}.jpg" target="_blank" title="{t} poster (opens full size)"><img src="img/posters/{f}-thumb.jpg" alt="{t} poster" height="130"></a></div>' for f,t in MUSICAL_POSTERS)
    return f'''
<section class="block past-seasons" id="past-seasons">
  <div class="wrap">
    <div class="head"><div><div class="eyebrow">Since 1988</div><h2>Past seasons</h2></div></div>
    <p class="ps-intro">Plays, musicals, pantos, one-acts, readings and festival entries staged by Portal Players over the decades.</p>
    <div class="note" style="max-width:760px">This list is extensive, but it may not be complete. Know of a production we’ve missed, or spot a name or date to correct? Please email <a href="mailto:capitoltheatre@shaw.ca?subject=Past%20seasons">capitoltheatre@shaw.ca</a> so we can add it.</div>
    <div class="ps-grid">{''.join(blocks)}</div>
    <div class="ps-musicals">
      <h3>Past Musicals</h3>
      <p class="ps-note">Includes pantomimes.</p>
      <div class="ps-posters">{mps}</div>
      <ul>{mus}</ul>
    </div>
  </div>
</section>'''


def with_year(when, head):
    """Add the year to a month-only date, e.g. 'April' in 2017–18 -> 'April 2018'."""
    if not when or _re.search(r'\b(19|20)\d\d\b', when):
        return when
    m = _re.match(r'\s*([A-Za-z]+)', when)
    if not m:
        return when
    word = m.group(1).lower()
    hm = _re.match(r'(\d{4})(?:–(\d{2}))?$', head)
    if not hm:
        return when
    y1 = int(hm.group(1)); y2 = y1 + 1 if hm.group(2) else y1
    if word in _MONTHS:
        y = y1 if _MONTHS.index(word) >= 8 else y2   # seasons run September to August
    elif word == 'summer':
        y = y2
    else:
        return when
    sep = ', ' if _re.search(r'\d$', when) else ' '
    return f'{when}{sep}{y}'

def _season_pos(when, head):
    """Position of an entry within its season, by its first month (September first for split seasons)."""
    m=_re.search(r'(January|February|March|April|May|June|July|August|September|October|November|December|Summer)', when or '', _re.I)
    if not m: return None
    word=m.group(1).lower(); mo=7 if word=='summer' else _MONTHS.index(word)+1
    split='–' in head
    return (mo-9)%12 if split else mo   # split seasons: Sep=0 ... Aug=11

def _pnorm(x):
    x=_re.sub('<[^>]+>','',x).lower().replace('&amp;','and').replace('&','and').replace('’',"'")
    x=_re.sub(r'\(.*?\)','',x).strip(); x=_re.sub(r'^(stages|stages year-end show)\s*:\s*','',x)
    x=_re.sub(r'^(the|a|an)\s+','',x.strip())
    return _re.sub(r'[^a-z0-9 ]','',x).strip()

def poster_slots(head, entries):
    """Which entry each of a season's posters belongs beside: {stem: index}, or 'host' for a festival poster."""
    out={}
    for f,t in POSTERS.get(head,[]):
        if ('drama-festival' in f or 'mainstage' in f) and head in HOSTED: out[f]='host'; continue
        pt=_pnorm(t) if t.startswith('An Evening') else _pnorm(t.split(':')[0])
        hits=[i for i,(w,ti,d) in enumerate(entries) if pt and (_pnorm(ti).startswith(pt[:14]) or pt.startswith(_pnorm(ti)[:14]))]
        if len(hits)!=1: hits=[i for i,(w,ti,d) in enumerate(entries) if pt[:14] in _pnorm(ti+' '+d)]
        if hits: out[f]=hits[0]
    return out


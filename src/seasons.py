def archive_html(head, title):
    a = next((v for (h, t), v in ARCHIVE.items() if h == head and t in title), None)
    if not a: return ''
    out = ''
    if a.get('hero'):
        f, cap = a['hero']
        alt = _re.sub('<[^>]+>', '', cap)
        out += (f'<figure class="ar-hero"><a href="img/archive/{f}.jpg" target="_blank" title="Open full size">'
                f'<img src="img/archive/{f}-wide.jpg" alt="{alt}" loading="lazy"></a><figcaption>{cap}</figcaption></figure>')
    out += f'<p class="ar-lead">{a["lead"]}</p>' if a.get('lead') else ''
    for name, sub, rows in a.get('awards', []):
        lis = ''.join(f'<div class="ar-aw"><b>{k}</b>{"<span>" + v + "</span>" if v else ""}</div>' for k, v in rows)
        out += f'<div class="ar-awards"><h4><span class="ar-ico" aria-hidden="true">🏆</span>{name}</h4><p class="ar-sub">{sub}</p>{lis}</div>'
    for gname, gcast, gteam in a.get('groups', []):
        rows = ''.join(f'<div class="ar-cr"><dt>{who}</dt><dd><em>{part}</em></dd></div>' for who, part in gcast)
        trows = ''.join(f'<div class="ar-cr"><dt>{k}</dt><dd>{v}</dd></div>' for k, v in gteam)
        out += f'<div class="ar-sec"><h4><span class="ar-ico" aria-hidden="true">🎭</span><span>{gname}</span></h4>'
        if rows: out += f'<p class="ar-sub">Cast</p><dl class="ar-credits">{rows}</dl>'
        if trows: out += f'<p class="ar-sub">Production team</p><dl class="ar-credits">{trows}</dl>'
        out += '</div>'
    if a.get('cast'):
        rows = ''.join((f'<div class="ar-cr"><dt>{who}</dt><dd><em>{part}</em></dd></div>' if part else f'<div class="ar-cr ar-cr1"><dt>{who}</dt></div>') for who, part in a['cast'])
        out += f'<div class="ar-sec"><h4><span class="ar-ico" aria-hidden="true">🎭</span>Cast</h4><dl class="ar-credits">{rows}</dl></div>'
    if a.get('credits'):
        rows = ''.join(f'<div class="ar-cr"><dt>{k}</dt><dd>{v}</dd></div>' for k, v in a['credits'])
        head = 'Production team' if a.get('cast') else ('Shared production team' if a.get('groups') else 'Cast &amp; crew')
        ico = STAGE_LIGHT if (a.get('cast') or a.get('groups')) else '🎭'
        out += f'<div class="ar-sec"><h4><span class="ar-ico" aria-hidden="true">{ico}</span>{head}</h4><dl class="ar-credits">{rows}</dl></div>'
    if a.get('notes'):
        out += '<div class="ar-sec ar-notes">' + ''.join(f'<p>{n}</p>' for n in a['notes']) + '</div>'
    for q, who in a.get('quotes', []):
        out += f'<blockquote class="ar-quote ar-q-sm">“{q}”<cite>{who}</cite></blockquote>'
    if a.get('quote'):
        q, who = a['quote']
        out += f'<blockquote class="ar-quote">“{q}”<cite>{who}</cite></blockquote>'
    if a.get('photos'):
        import os
        from PIL import Image
        here = os.path.dirname(os.path.abspath(__file__))
        figs = ''
        for f, cap in a['photos']:
            try:
                with Image.open(os.path.join(here, '..', 'img', 'archive', f + '-thumb.jpg')) as im: w, h = im.size
            except Exception: w, h = 300, 200
            figs += f'<figure><a href="img/archive/{f}.jpg" target="_blank" title="Open full size"><img src="img/archive/{f}-thumb.jpg" alt="{_re.sub("<[^>]+>", "", cap)}" width="{w}" height="{h}" loading="lazy"></a><figcaption>{cap}</figcaption></figure>'
        out += f'<div class="ar-photos">{figs}</div>'
    if a.get('videos'):
        vids = ''
        for t, c, u in a['videos']:
            m = _re.search(r'v=([\w-]{11})(?:&t=(\d+))?', u)
            vid, start = m.group(1), m.group(2) or ''
            plain = _re.sub(r'<[^>]+>', '', t)
            vids += (f'<figure class="ar-vid"><button type="button" class="ar-yt" data-yt="{vid}" data-start="{start}" aria-label="Play video: {plain}">'
                     f'<img src="https://i.ytimg.com/vi/{vid}/hqdefault.jpg" alt="" width="480" height="360" loading="lazy"><span class="ar-play" aria-hidden="true"></span></button>'
                     f'<figcaption>{t} <span class="ar-src">· {_credit(c)} · <a href="{u}" target="_blank" rel="noopener">YouTube</a></span></figcaption></figure>')
        out += f'<div class="ar-vids">{vids}</div>'
    if a.get('links'):
        out += '<div class="ar-links">' + ''.join(f'<p><span aria-hidden="true">{i}</span><a href="{u}" target="_blank" rel="noopener">{t}</a></p>' for i, t, u in a['links']) + '</div>'
    for t, c, src, poster in a.get('clips', []):
        out += (f'<div class="ar-vids"><figure class="ar-vid ar-clip"><video controls preload="none" playsinline poster="{poster}" width="480" height="360">'
                f'<source src="{src}" type="video/mp4"></video><figcaption>{t} <span class="ar-src">· {_credit(c)}</span></figcaption></figure></div>')
    parts = [w for w, k in (('awards', 'awards'), ('cast', 'groups'), ('cast', 'cast'), ('team', 'credits'), ('notes', 'notes'), ('photos', 'photos'), ('video', 'videos'), ('news', 'links')) if a.get(k) or (k == 'photos' and a.get('hero')) or (k == 'videos' and a.get('clips'))]
    if a.get('videos') and len(a['videos']) > 1: parts[parts.index('video')] = 'videos'
    parts = [x for i, x in enumerate(parts) if x != 'cast' or 'cast' not in parts[:i]]
    if 'team' in parts and not (a.get('cast') or a.get('groups')): parts[parts.index('team')] = 'cast'
    if 'cast' in parts and 'team' in parts: parts.remove('team'); parts[parts.index('cast')] = 'cast'
    if len(parts) == 1: label = parts[0]
    elif len(parts) == 2: label = f'{parts[0]} &amp; {parts[1]}'
    elif len(parts) == 3 and len(''.join(parts)) <= 16: label = f'{parts[0]}, {parts[1]} &amp; {parts[2]}'
    else: label = f'{parts[0]}, {parts[1]} &amp; more'
    label = label[0].upper() + label[1:]
    return f'<details class="ar"><summary><span class="ar-tag">From the archive</span><span class="ar-lbl">{label}</span></summary><div class="ar-body">{out}</div></details>'


def festivals_callout():
    """The Theatre BC festivals we hosted: a larger poster (or the Theatre BC logo while one is missing) beside each festival's playbill."""
    rows = ''
    for year, title, dates, where, stem, plays in FESTIVALS:
        if stem:
            from PIL import Image
            import os
            here = os.path.dirname(os.path.abspath(__file__))
            with Image.open(os.path.join(here, '..', 'img', 'posters', stem + '-med.jpg')) as im: w, h = im.size
            pic = f'<a href="img/posters/{stem}.jpg?v={_v(stem)}" target="_blank" title="{year} {title} poster (opens full size)"><img src="img/posters/{stem}-med.jpg?v={_v(stem + "-med")}" alt="{year} {title} poster" width="{w}" height="{h}" loading="lazy"></a>'
        else:
            pic = '<div class="pf-logo"><img src="img/theatre-bc.png" alt="Theatre BC logo" width="120" height="121" loading="lazy"><span>Poster to come</span></div>'
        if plays:
            li = ''.join(f'<li><span class="pf-d">{d}</span><span class="pf-t">{"<em>" + t + "</em>" if c or b else "<b>" + t + "</b>"}{" <span class=pf-by>" + b + "</span>" if b else ""}{"<span class=pf-c>" + c + "</span>" if c else ""}</span></li>' for d, t, b, c in plays)
            lst = f'<ul class="pf-list">{li}</ul>'
        else:
            lst = '<p class="pf-soon">The playbill for this festival is coming soon.</p>'
        vid = ''.join(f'<p class="pf-video"><span aria-hidden="true">▶</span> <a href="{u}" target="_blank" rel="noopener">{t}</a> <span class="pf-vsrc">(video)</span></p>' for t, u in FEST_VIDEOS.get(str(year), []))
        rows += f'<div class="pf-row" id="fest-{year}"><div class="pf-pic">{pic}</div><div class="pf-info"><div class="pf-year">{year}</div><h4>{title}</h4><p class="pf-dates">{dates}</p><p class="pf-where">{where}</p>{lst}{vid}</div></div>'
    results = ''
    for rt, note, awards in FEST_RESULTS:
        li = ''.join(f'<li{" class=pp" if c == "Portal Players" else ""}><span class="pr-a">{a}</span><span class="pr-w">{(c + (" · <em>" + pl + "</em>" if pl else "")) if c else ""}{(" · " if c else "") + "<b>" + who + "</b>" if who else ""}</span></li>' for a, c, pl, who in awards)
        results += f'<div class="pf-results"><h4>{rt}</h4><p class="pf-where">{note}</p><ul>{li}</ul></div>'
    return f"""<div class="ps-musicals ps-fests" id="festivals">
      <div class="pf-head"><div class="pf-ht"><img class="pf-tbc" src="img/theatre-bc.png" alt="Theatre BC" width="238" height="240" loading="lazy"><h3>Theatre BC Festivals We’ve Hosted</h3></div></div>
      <p class="ps-note">North Island Zone drama festivals at The Capitol Theatre, and the 2019 provincial Mainstage festival at the ADSS Performing Arts Theatre.</p>
      {rows}
      {results}
    </div>
    <p class="ps-top"><a href="#past-seasons">↑ Scroll back to the top of the list</a></p>"""

def stages_callout(more=''):
    """The Past STAGES Productions box, gathered from the season lists (used on the history and STAGES pages)."""
    # STAGES callout, gathered from the season lists
    st_items=[]; st_pics=[]
    for head,note,entries in SEASONS:
        slots=poster_slots(head, entries)
        for idx,(when,title,detail) in enumerate(entries):
            if 'STAGES' not in title: continue
            wy=with_year(when, head); m=_re.search(r'(19|20)\d\d',wy); y=m.group(0) if m else head[:4]
            mon=_re.sub(r',?\s*(19|20)\d\d','',wy).strip()
            t=_re.sub(r'^STAGES( year-end show)?:\s*','',title)
            st_items.append(f'<li><span class="ps-when">{y}{" · "+mon if mon else ""}</span><span class="ps-title">{t}</span></li>')
            for f,pt in POSTERS.get(head,[]):
                if slots.get(f)==idx and f not in NOLINK and 'alternate' not in f:
                    w,h=_thumb_size(f)
                    st_pics.append(f'<div class="ps-pfig"><span class="ps-when ps-pyear">{y}</span><a href="img/posters/{f}.jpg?v={_v(f)}" target="_blank" title="{pt} poster (opens full size)"><img src="img/posters/{f}-thumb.jpg?v={_v(f+"-thumb")}" alt="{pt} poster" width="{round(w*130/h)}" height="130" loading="lazy"></a></div>')
    stl=''.join(st_items); sps=''.join(st_pics)
    return f'''<div class="ps-musicals ps-stages">
      <h3>Past STAGES Productions</h3>
      <p class="ps-note">Our STAGES Youth Theatre program.{more}</p>
      <div class="ps-posters">{sps}</div>
      <ul>{stl}</ul>
    </div>'''


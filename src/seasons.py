def render():
    blocks=[]
    for head, note, entries in SEASONS:
        lis=''
        for when, title, detail in entries:
            w=f'<span class="ps-when">{when}</span>' if when else ''
            d=f'<span class="ps-detail">{detail}</span>' if detail else ''
            t2=title if '<em>' in title else f'<b>{title}</b>'
            lis+=f'<li>{w}<span class="ps-title">{t2}</span>{d}</li>'
        n=f'<p class="ps-note">{note}</p>' if note else ''
        ps=''.join(f'<a href="img/posters/{f}.jpg" target="_blank" title="{t} poster (opens full size)"><img src="img/posters/{f}-thumb.jpg" alt="{t} poster" height="130" loading="lazy"></a>' for f,t in POSTERS.get(head,[]))
        ps=f'<div class="ps-posters">{ps}</div>' if ps else ''
        blocks.append(f'<div class="ps-season">{ps}<h3>{head}</h3>{n}<ul>{lis}</ul></div>')
    mus=''.join(f'<li><span class="ps-when">{y} · {m}</span><span class="ps-title"><em>{t.replace(" (panto)","")}</em>{" (panto)" if "(panto)" in t else ""}</span></li>' for y,m,t in MUSICALS)
    return f'''
<section class="block past-seasons" id="past-seasons">
  <div class="wrap">
    <div class="head"><div><div class="eyebrow">Since 1988</div><h2>Past seasons</h2></div></div>
    <p class="ps-intro">Plays, musicals, pantos, one-acts, readings and festival entries staged by Portal Players over the decades.</p>
    <div class="note" style="max-width:760px">This list is extensive, but it may not be complete. Know of a production we’ve missed, or spot a name or date to correct? Please email <a href="mailto:capitoltheatre@shaw.ca?subject=Past%20seasons">capitoltheatre@shaw.ca</a> so we can add it.</div>
    <div class="ps-grid">{''.join(blocks)}</div>
    <div class="ps-musicals">
      <h3>Past musicals</h3>
      <p class="ps-note">Includes pantomimes.</p>
      <ul>{mus}</ul>
    </div>
  </div>
</section>'''

